def create_similarity_matrix(cities):
    """创建方言相似度矩阵"""
    n = len(cities)
    similarity = np.eye(n)
    
    # 根据语言亲缘关系设置相似度
    similarity_rules = [
        (0, 9, 0.85),  # 北京-哈尔滨：官话
        (1, 10, 0.92), # 上海-苏州：吴语
        (2, 8, 0.75),  # 广州-梅州：粤语-客家话
        (3, 0, 0.70),  # 成都-北京：西南官话-北京官话
        (4, 0, 0.80),  # 西安-北京：中原官话-北京官话
        (5, 6, 0.72),  # 长沙-南昌：湘语-赣语
        (7, 11, 0.78), # 福州-厦门：闽语
        (2, 11, 0.65), # 广州-厦门：粤语-闽南语
        (1, 5, 0.60),  # 上海-长沙：吴语-湘语
        (6, 3, 0.68),  # 南昌-成都：赣语-西南官话
    ]
    
    for i, j, sim in similarity_rules:
        similarity[i, j] = sim
        similarity[j, i] = sim
    
    # 其他相似度基于地理距离计算
    coords = {
        '北京': (116.4074, 39.9042), '上海': (121.4737, 31.2304),
        '广州': (113.2644, 23.1291), '成都': (104.0668, 30.5728),
        '西安': (108.9480, 34.2619), '长沙': (112.9388, 28.2281),
        '南昌': (115.8921, 28.6898), '福州': (119.3062, 26.0753),
        '梅州': (116.1134, 24.2945), '哈尔滨': (126.6425, 45.8038),
        '苏州': (120.6204, 31.3280), '厦门': (118.0819, 24.4798)
    }
    
    for i in range(n):
        for j in range(n):
            if i != j and similarity[i, j] == 1.0:
                lon1, lat1 = coords[cities[i]]
                lon2, lat2 = coords[cities[j]]
                distance = np.sqrt((lon1-lon2)**2 + (lat1-lat2)**2)
                similarity[i, j] = max(0.3, 1 - distance / 40)
    
    df = pd.DataFrame(similarity, index=cities, columns=cities)
    return df

