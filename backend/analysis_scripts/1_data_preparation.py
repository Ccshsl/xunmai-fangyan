    similarity_matrix.to_csv(DIALECT_SIMILARITY_FILE, encoding='utf-8-sig')
    print(f"   已创建: {DIALECT_SIMILARITY_FILE}")
    
    print("\n[步骤3] 创建方言区人口统计表...")
    population_stats = create_population_statistics(dialect_points)
    population_stats.to_csv(POPULATION_FILE, index=False, encoding='utf-8-sig')
    print(f"   已创建: {POPULATION_FILE}")
    
    print("\n[步骤4] 创建特征词对照表...")
    feature_words = create_feature_words()
    feature_words.to_csv(FEATURE_WORDS_FILE, index=False, encoding='utf-8-sig')
    print(f"   已创建: {FEATURE_WORDS_FILE}")
    
    print("\n" + "=" * 60)
    print("数据准备完成！")
    print("=" * 60)
    
    return dialect_points, similarity_matrix, population_stats, feature_words

